-- Radar Cívico: atualização semanal nacional de receitas por UF e municipal SP.
-- O coletor espaça as requisições em 1 minuto e só publica demonstrativos completos.
create table if not exists internal.coletas_receitas(
 id bigint generated by default as identity primary key,
 request_id bigint not null unique,
 ente integer not null,
 exercicio integer not null,
 periodo integer not null,
 status text not null default 'pendente' check(status in('pendente','concluida','sem_dados','erro')),
 quantidade integer, erro text,
 solicitada_em timestamptz not null default now(),
 processada_em timestamptz
);
revoke all on internal.coletas_receitas from public,anon,authenticated;

CREATE OR REPLACE FUNCTION internal.solicitar_proxima_receita()
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'internal', 'public'
AS $function$
declare
 v_ente integer;v_ano integer;v_periodo integer;v_mes integer;v_request bigint;
begin
 v_mes := extract(month from current_date)::int;
 if v_mes <= 2 then
  v_ano:=extract(year from current_date)::int-1;
  v_periodo:=6;
 else
  v_ano:=extract(year from current_date)::int;
  v_periodo:=(v_mes-1)/2;
 end if;
 with candidatos as(
   select id_ente from internal.entes_siconfi where ativo
   union all select 3550308 as id_ente
 )
 select e.id_ente into v_ente from candidatos e
 where not exists(
  select 1 from internal.coletas_receitas r where r.ente=e.id_ente
  and r.exercicio=v_ano and r.periodo=v_periodo
  and r.solicitada_em>=date_trunc('week',now())
 )
 order by case when e.id_ente=3550308 then 0 else 1 end,e.id_ente limit 1;
 if v_ente is null then return null;end if;
 select net.http_get(
  url:='https://apidatalake.tesouro.gov.br/ords/cdwhprd/siconfi/tt/rreo',
  params:=jsonb_build_object(
   'an_exercicio',v_ano::text,'nr_periodo',v_periodo::text,
   'co_tipo_demonstrativo','RREO','no_anexo','RREO-Anexo 01','id_ente',v_ente::text),
  timeout_milliseconds:=20000
 ) into v_request;
 insert into internal.coletas_receitas(request_id,ente,exercicio,periodo)
 values(v_request,v_ente,v_ano,v_periodo);
 return v_request;
end;
$function$
;
CREATE OR REPLACE FUNCTION internal.processar_receitas()
 RETURNS integer
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'internal', 'public'
AS $function$
declare
 j record; v_body jsonb; v_count integer;v_total integer:=0;v_url text;
begin
 for j in select c.id,c.ente,c.exercicio,c.periodo,r.content,r.status_code,r.error_msg
  from internal.coletas_receitas c join net._http_response r on r.id=c.request_id
  where c.status='pendente' order by c.id
 loop
  begin
   if j.status_code is distinct from 200 then
    update internal.coletas_receitas set status='erro',
     erro='HTTP '||coalesce(j.status_code::text,'nulo')||' '||coalesce(j.error_msg,''),
     processada_em=now() where id=j.id;
    continue;
   end if;
   v_body:=j.content::jsonb;
   if jsonb_typeof(v_body->'items') <> 'array' or v_body->>'hasMore'<>'false' then
    raise exception 'Resposta de receitas incompleta ou paginada';
   end if;
   if jsonb_array_length(v_body->'items') < 50 then
    update internal.coletas_receitas set status='sem_dados',erro='Demonstrativo não publicado ou insuficiente',
     processada_em=now() where id=j.id;
    continue;
   end if;
   v_url:=format('https://apidatalake.tesouro.gov.br/ords/cdwhprd/siconfi/tt/rreo?an_exercicio=%s&nr_periodo=%s&co_tipo_demonstrativo=RREO&no_anexo=RREO-Anexo%%2001&id_ente=%s',
     j.exercicio,j.periodo,j.ente);
   with item as(
    select x from jsonb_array_elements(v_body->'items') x
    where x->>'cod_ibge'=j.ente::text
      and x->>'exercicio'=j.exercicio::text
      and x->>'periodo'=j.periodo::text
      and x->>'esfera'=case when j.ente=3550308 then 'M' else 'E' end
      and x->>'anexo'='RREO-Anexo 01'
      and x->>'cod_conta'=any(array[
        'ReceitasExcetoIntraOrcamentarias','ReceitasCorrentes','ReceitasDeCapital',
        'ReceitaTributaria','Impostos','Taxas','ContribuicoesDeMelhoria',
        'TransferenciasCorrentes','OutrasReceitasCorrentes','Contribuicoes']::text[])
   ), piv as(
    select x->>'cod_conta' as codigo,max(x->>'conta') as nome,
     max(x->>'uf') as uf,max(x->>'instituicao') as instituicao,
     max((x->>'valor')::numeric) filter(where x->>'coluna'='PREVISÃO ATUALIZADA (a)') as previsto,
     max((x->>'valor')::numeric) filter(where x->>'coluna'='Até o Bimestre (c)') as realizado
    from item group by x->>'cod_conta'
   ), up as (
    insert into public.receitas_publicas(
     ente_id,ano_referencia,periodo,esfera,uf,municipio,orgao_responsavel,
     codigo_conta,nome_conta,valor_previsto,valor_realizado,fonte_url,data_consulta,origem_base)
    select j.ente,j.exercicio,j.periodo,
      case when j.ente=3550308 then 'Municipal' when j.ente=53 then 'Distrital' else 'Estadual' end,
      uf,case when j.ente=3550308 then 'São Paulo' else null end,instituicao,
      codigo,nome,previsto,realizado,v_url,current_date,'SICONFI-RREO-Anexo01'
    from piv where realizado is not null and uf is not null and instituicao is not null
    on conflict(ente_id,ano_referencia,codigo_conta,origem_base) do update set
      periodo=excluded.periodo,esfera=excluded.esfera,
      uf=excluded.uf,municipio=excluded.municipio,orgao_responsavel=excluded.orgao_responsavel,
      nome_conta=excluded.nome_conta,valor_previsto=excluded.valor_previsto,
      valor_realizado=excluded.valor_realizado,fonte_url=excluded.fonte_url,
      data_consulta=excluded.data_consulta,atualizado_em=now()
    returning id
   ) select count(*) into v_count from up;
   if v_count < 3 then raise exception 'Poucos indicadores de receita: %',v_count;end if;
   update internal.coletas_receitas set status='concluida',quantidade=v_count,erro=null,processada_em=now()
   where id=j.id;
   v_total:=v_total+v_count;
  exception when others then
   update internal.coletas_receitas set status='erro',erro=left(sqlerrm,500),processada_em=now()
   where id=j.id;
  end;
 end loop;
 return v_total;
end;
$function$
;
revoke all on function internal.solicitar_proxima_receita() from public,anon,authenticated;
revoke all on function internal.processar_receitas() from public,anon,authenticated;
select cron.schedule('radar-civico-receitas-consultar','0-58 9 * * 2',
  'select internal.solicitar_proxima_receita();');
select cron.schedule('radar-civico-receitas-processar','*/5 9 * * 2',
  'select internal.processar_receitas();');
